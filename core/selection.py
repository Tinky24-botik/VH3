def extract_number(text: str) -> int | None:
    """
    Извлекает номер варианта из текста.

    Поддерживает:

    1
    "1"
    "первый"
    "один"
    "номер один"
    "вариант один"
    "номер 1"
    "вариант 1"
    """

    text = (
        text
        .lower()
        .strip()
    )

    if not text:
        return None

    # ---------------------------------------------
    # Убираем типичные слова перед номером
    # ---------------------------------------------

    text = re.sub(
        r"^(номер|вариант)\s+",
        "",
        text,
    )

    # ---------------------------------------------
    # Если после очистки осталось число
    # ---------------------------------------------

    if text.isdigit():
        return int(text)

    # ---------------------------------------------
    # Проверяем точное числительное
    # ---------------------------------------------

    if text in NUMBER_WORDS:
        return NUMBER_WORDS[text]

    # ---------------------------------------------
    # Иногда STT может вернуть лишние слова.
    #
    # Например:
    #
    # "первый вариант"
    # "вариант второй"
    # ---------------------------------------------

    words = text.split()

    for word in words:
        if word.isdigit():
            return int(word)

        if word in NUMBER_WORDS:
            return NUMBER_WORDS[word]

    return None


def resolve_selection(
    text: str,
    options: list,
) -> int | None:
    """
    Преобразует голосовой/текстовый ответ
    в индекс выбранного варианта.

    Возвращает индекс начиная с 0.

    Например:

    "первый" -> 0
    "один"   -> 0
    "1"      -> 0

    "второй" -> 1
    "два"    -> 1
    "2"      -> 1
    """

    number = extract_number(text)

    if number is None:
        return None

    # Пользователь видит варианты начиная с 1,
    # Python-индекс начинается с 0.

    index = number - 1

    if index < 0:
        return None

    if index >= len(options):
        return None

    return index